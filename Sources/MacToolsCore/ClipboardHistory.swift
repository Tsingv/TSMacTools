import Foundation

/// Maccy-equivalent clipboard history policy and in-memory store.
/// Representations are opaque pasteboard type/data pairs so paste restores every
/// captured format instead of collapsing to plain text.
public struct ClipboardSettings: Equatable, Codable, Sendable {
    public static let defaultHistorySize = 200
    public static let defaultCheckInterval: TimeInterval = 0.5
    public static let historySizeRange = 10 ... 10_000
    public static let checkIntervalRange: ClosedRange<TimeInterval> = 0.1 ... 5

    /// Types Maccy always ignores (confidential or temporary).
    public static let builtInIgnoredTypes: [String] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    /// Removable defaults matching Maccy's shipped ignore list.
    public static let defaultIgnoredTypes: [String] = [
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    public static let preferredTypes: [String] = [
        "public.utf8-plain-text",
        "public.rtf",
        "public.html",
        "public.png",
        "public.tiff",
        "public.file-url"
    ]

    public static let unpersistableTypePrefixes = ["dyn.", "com.microsoft.ole.source."]
    public static let unpersistableTypes: Set<String> = [
        "com.apple.webarchive",
        "com.apple.Safari.WebArchive"
    ]

    public var enabled: Bool
    public var historySize: Int
    public var pasteAutomatically: Bool
    public var showFooter: Bool
    public var checkInterval: TimeInterval
    public var ignoreEvents: Bool
    public var ignoreOnlyNextEvent: Bool
    public var ignoreAllAppsExceptListed: Bool
    public var ignoredApps: [String]
    public var ignoredPasteboardTypes: [String]
    public var ignoreRegex: [String]
    public var clearSystemClipboard: Bool

    public init(
        enabled: Bool = true,
        historySize: Int = ClipboardSettings.defaultHistorySize,
        pasteAutomatically: Bool = true,
        showFooter: Bool = true,
        checkInterval: TimeInterval = ClipboardSettings.defaultCheckInterval,
        ignoreEvents: Bool = false,
        ignoreOnlyNextEvent: Bool = false,
        ignoreAllAppsExceptListed: Bool = false,
        ignoredApps: [String] = [],
        ignoredPasteboardTypes: [String] = ClipboardSettings.defaultIgnoredTypes,
        ignoreRegex: [String] = [],
        clearSystemClipboard: Bool = false
    ) {
        self.enabled = enabled
        self.historySize = historySize
        self.pasteAutomatically = pasteAutomatically
        self.showFooter = showFooter
        self.checkInterval = checkInterval
        self.ignoreEvents = ignoreEvents
        self.ignoreOnlyNextEvent = ignoreOnlyNextEvent
        self.ignoreAllAppsExceptListed = ignoreAllAppsExceptListed
        self.ignoredApps = ignoredApps
        self.ignoredPasteboardTypes = ignoredPasteboardTypes
        self.ignoreRegex = ignoreRegex
        self.clearSystemClipboard = clearSystemClipboard
    }

    public static let `default` = ClipboardSettings()

    public var sanitized: ClipboardSettings {
        var copy = self
        copy.historySize = min(max(historySize, Self.historySizeRange.lowerBound), Self.historySizeRange.upperBound)
        copy.checkInterval = min(max(checkInterval, Self.checkIntervalRange.lowerBound), Self.checkIntervalRange.upperBound)
        copy.ignoredApps = ignoredApps.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        copy.ignoredPasteboardTypes = ignoredPasteboardTypes.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        copy.ignoreRegex = ignoreRegex.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        return copy
    }

    public func shouldIgnore(types: Set<String>) -> Bool {
        let ignored = Set(Self.builtInIgnoredTypes + sanitized.ignoredPasteboardTypes)
        if types.isDisjoint(with: Set(Self.preferredTypes)) { return true }
        if !types.isDisjoint(with: ignored) { return true }
        return false
    }

    public func shouldIgnore(application bundleIdentifier: String?) -> Bool {
        guard let bundleIdentifier, !bundleIdentifier.isEmpty else { return false }
        let listed = Set(sanitized.ignoredApps)
        if ignoreAllAppsExceptListed {
            return !listed.contains(bundleIdentifier)
        }
        return listed.contains(bundleIdentifier)
    }

    public func shouldIgnore(plainText: String?) -> Bool {
        guard let plainText else { return false }
        for pattern in sanitized.ignoreRegex {
            guard let regex = try? NSRegularExpression(pattern: pattern) else { continue }
            let range = NSRange(plainText.startIndex..., in: plainText)
            if regex.numberOfMatches(in: plainText, range: range) > 0 {
                return true
            }
        }
        return false
    }

    public static func isPersistableType(_ type: String) -> Bool {
        if unpersistableTypes.contains(type) { return false }
        return !unpersistableTypePrefixes.contains { type.hasPrefix($0) }
    }
}

public struct ClipboardRepresentation: Equatable, Codable, Sendable {
    public var type: String
    public var data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }

    public var plainText: String? {
        guard type == "public.utf8-plain-text" || type == "public.utf16-plain-text" || type == "NSStringPboardType" else {
            return nil
        }
        return String(data: data, encoding: .utf8) ?? String(data: data, encoding: .utf16)
    }
}

public struct ClipboardHistoryItem: Equatable, Codable, Sendable, Identifiable {
    public var id: UUID
    public var representations: [ClipboardRepresentation]
    public var application: String?
    public var title: String
    public var pinned: Bool
    public var createdAt: Date
    public var pinShortcut: String?

    public init(
        id: UUID = UUID(),
        representations: [ClipboardRepresentation],
        application: String? = nil,
        title: String? = nil,
        pinned: Bool = false,
        createdAt: Date = Date(),
        pinShortcut: String? = nil
    ) {
        self.id = id
        self.representations = representations
        self.application = application
        self.pinned = pinned
        self.createdAt = createdAt
        self.pinShortcut = pinShortcut
        self.title = title ?? Self.generatedTitle(from: representations)
    }

    public var plainText: String? {
        representations.compactMap(\.plainText).first { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
    }

    public var previewImageData: Data? {
        representations.first { $0.type == "public.png" || $0.type == "public.tiff" }?.data
    }

    public var plainTextRepresentations: [ClipboardRepresentation] {
        let strings = representations.filter { $0.plainText != nil }
        let files = representations.filter { $0.type == "public.file-url" }
        if strings.isEmpty { return representations }
        return strings + files
    }

    public static func generatedTitle(from representations: [ClipboardRepresentation]) -> String {
        if let text = representations.compactMap(\.plainText).first,
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let collapsed = text.replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            return String(collapsed.prefix(200))
        }
        if representations.contains(where: { $0.type == "public.file-url" }) {
            let count = representations.filter { $0.type == "public.file-url" }.count
            return count == 1 ? "File" : "\(count) Files"
        }
        if representations.contains(where: { $0.type == "public.png" || $0.type == "public.tiff" }) {
            return "Image"
        }
        if representations.contains(where: { $0.type == "public.html" || $0.type == "public.rtf" }) {
            return "Rich Text"
        }
        return representations.first.map { "Clipboard (\($0.type))" } ?? "Clipboard"
    }

    /// Fingerprint used to collapse an immediate duplicate copy of the same payload.
    public var contentIdentity: String {
        representations.map { "\($0.type):\($0.data.count):\($0.data.hashValue)" }.sorted().joined(separator: "|")
    }
}

public struct ClipboardHistoryStore: Equatable, Codable, Sendable {
    public private(set) var items: [ClipboardHistoryItem]
    public var settings: ClipboardSettings

    public init(items: [ClipboardHistoryItem] = [], settings: ClipboardSettings = .default) {
        self.items = items
        self.settings = settings.sanitized
    }

    public var orderedItems: [ClipboardHistoryItem] {
        let pinned = items.filter(\.pinned)
        let rest = items.filter { !$0.pinned }
        return pinned + rest
    }

    @discardableResult
    public mutating func record(_ item: ClipboardHistoryItem) -> ClipboardHistoryItem? {
        let settings = self.settings.sanitized
        guard settings.enabled, !settings.ignoreEvents else {
            if settings.ignoreOnlyNextEvent {
                self.settings.ignoreEvents = false
                self.settings.ignoreOnlyNextEvent = false
            }
            return nil
        }
        let types = Set(item.representations.map(\.type))
        if settings.shouldIgnore(types: types) { return nil }
        if settings.shouldIgnore(application: item.application) { return nil }
        if settings.shouldIgnore(plainText: item.plainText) { return nil }

        let kept = item.representations.filter { ClipboardSettings.isPersistableType($0.type) && !$0.data.isEmpty }
        guard !kept.isEmpty else { return nil }
        if kept.allSatisfy({ $0.plainText?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == true })
            && !kept.contains(where: { $0.type == "public.rtf" || $0.type == "public.html" || $0.type == "public.png" || $0.type == "public.tiff" || $0.type == "public.file-url" }) {
            return nil
        }

        var stored = ClipboardHistoryItem(
            id: item.id,
            representations: kept,
            application: item.application,
            pinned: false,
            createdAt: item.createdAt
        )
        if let existing = items.first(where: { $0.contentIdentity == stored.contentIdentity }) {
            items.removeAll { $0.id == existing.id }
            stored.pinned = existing.pinned
            stored.pinShortcut = existing.pinShortcut
        }
        items.insert(stored, at: 0)
        trim()
        return stored
    }

    public mutating func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        if items[index].pinned, items[index].pinShortcut == nil {
            let used = Set(items.compactMap(\.pinShortcut))
            let alphabet = "abcdefghijklmnopqrstuvwxyz0123456789"
            items[index].pinShortcut = alphabet.first { !used.contains(String($0)) }.map(String.init)
        }
        if !items[index].pinned {
            items[index].pinShortcut = nil
        }
    }

    public mutating func delete(_ id: UUID) {
        items.removeAll { $0.id == id }
    }

    public mutating func clear(includingPinned: Bool) {
        if includingPinned {
            items.removeAll()
        } else {
            items.removeAll { !$0.pinned }
        }
    }

    public func filtered(query: String) -> [ClipboardHistoryItem] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let source = orderedItems
        guard !trimmed.isEmpty else { return source }
        return source.filter { item in
            item.title.localizedCaseInsensitiveContains(trimmed)
                || (item.plainText?.localizedCaseInsensitiveContains(trimmed) == true)
                || item.representations.contains { $0.type.localizedCaseInsensitiveContains(trimmed) }
        }
    }

    public mutating func apply(settings: ClipboardSettings) {
        self.settings = settings.sanitized
        trim()
    }

    private mutating func trim() {
        let limit = settings.sanitized.historySize
        let pinned = items.filter(\.pinned)
        var unpinned = items.filter { !$0.pinned }
        if unpinned.count > limit {
            unpinned = Array(unpinned.prefix(limit))
        }
        items = pinned + unpinned
        if items.count > limit + pinned.count {
            items = Array(items.prefix(limit + pinned.count))
        }
    }
}
